local function luminance(hex)
  local function lin(part)
    local c = tonumber(part, 16) / 255
    if c <= 0.04045 then return c / 12.92 end
    return ((c + 0.055) / 1.055) ^ 2.4
  end
  return 0.2126 * lin(hex:sub(2, 3))
       + 0.7152 * lin(hex:sub(4, 5))
       + 0.0722 * lin(hex:sub(6, 7))
end

local function mix(color, pct, target)
  return string.format("color-mix(in srgb, %s %d%%, %s)", color, 100 - pct, target)
end

local function read_palette(path)
  local file = assert(io.open(path, "r"))
  local palette = {}
  local section

  for raw_line in file:lines() do
    local line = raw_line:gsub("^%s+", ""):gsub("%s+$", "")

    if line:match("^%[.+%]$") then
      section = line:match("^%[(.+)%]$")
      palette[section] = {}
    elseif line ~= "" and not line:match("^#") then
      local key, value = line:match('^([%w_]+)%s*=%s*"([^"]+)"')
      if key then
        assert(section, "Key outside section in " .. path)
        palette[section][key] = value
      end
    end
  end

  file:close()
  return palette
end

local function write(path, content)
  local file = assert(io.open(path, "w"))
  file:write(content)
  file:close()
  print("Generated " .. path)
end

local function slug(name)
  return name:lower():gsub("%s+", "-")
end

local function validate(p)
  local required = {
    ui = {"background", "surface", "foreground", "muted", "border", "selection", "cursor"},
    accent = {"primary", "secondary"},
    syntax = {"comment", "string", "number", "function", "keyword", "type", "constant", "operator", "preprocessor", "special"},
    status = {"error", "warning", "success", "info", "hint"},
    diff = {"added", "changed", "removed"},
  }

  assert(p.meta and p.meta.name, "Missing [meta].name")

  for section, keys in pairs(required) do
    assert(p[section], "Missing [" .. section .. "]")
    for _, key in ipairs(keys) do
      local value = p[section][key]
      assert(value and value:match("^#%x%x%x%x%x%x$"),
        "Invalid or missing " .. section .. "." .. key)
    end
  end
end

local function generate_nvim(p)
  local c = {}
  for section, values in pairs(p) do
    if section ~= "meta" then
      for key, value in pairs(values) do
        c[section .. "_" .. key] = value
      end
    end
  end

  local lines = {
    "-- Generated by scripts/generate.lua. Do not edit.",
    "",
    'vim.cmd("highlight clear")',
    'if vim.fn.exists("syntax_on") == 1 then vim.cmd("syntax reset") end',
    "vim.o.termguicolors = true",
    'vim.g.colors_name = "findspot-' .. slug(p.meta.name) .. '"',
    "",
    "local c = {",
  }

  for key, value in pairs(c) do
    lines[#lines + 1] = string.format("  [%q] = %q,", key, value)
  end

  lines[#lines + 1] = "}"
  lines[#lines + 1] = "local function hi(group, opts)"
  lines[#lines + 1] = "  vim.api.nvim_set_hl(0, group, opts)"
  lines[#lines + 1] = "end"
  lines[#lines + 1] = ""

  local groups = {
    {"Normal", "ui_foreground", "ui_background"},
    {"NormalNC", "ui_foreground", "ui_background"},
    {"NormalFloat", "ui_foreground", "ui_surface"},
    {"FloatBorder", "ui_border", "ui_surface"},
    {"SignColumn", "ui_muted", "ui_background"},
    {"EndOfBuffer", "ui_border", "ui_background"},
    {"LineNr", "ui_muted", "ui_background"},
    {"CursorLine", nil, "ui_surface"},
    {"CursorLineNr", "accent_secondary", "ui_surface"},
    {"VertSplit", "ui_border", "ui_background"},
    {"WinSeparator", "ui_border", "ui_background"},
    {"StatusLine", "ui_foreground", "ui_surface"},
    {"StatusLineNC", "ui_muted", "ui_surface"},
    {"Pmenu", "ui_foreground", "ui_surface"},
    {"PmenuSel", "ui_background", "accent_primary"},
    {"Visual", "ui_foreground", "ui_selection"},
    {"Search", "ui_background", "accent_secondary"},
    {"IncSearch", "ui_background", "ui_cursor"},
    {"MatchParen", "accent_primary", "ui_surface"},
    {"Folded", "ui_muted", "ui_surface"},
    {"Directory", "accent_primary"},
    {"Title", "accent_secondary"},
    {"ErrorMsg", "status_error"},
    {"WarningMsg", "status_warning"},
    {"Comment", "syntax_comment"},
    {"String", "syntax_string"},
    {"Character", "syntax_string"},
    {"Number", "syntax_number"},
    {"Float", "syntax_number"},
    {"Boolean", "syntax_constant"},
    {"Constant", "syntax_constant"},
    {"Identifier", "ui_foreground"},
    {"Function", "syntax_function"},
    {"Statement", "syntax_keyword"},
    {"Conditional", "syntax_keyword"},
    {"Repeat", "syntax_keyword"},
    {"Keyword", "syntax_keyword"},
    {"Operator", "syntax_operator"},
    {"Type", "syntax_type"},
    {"Structure", "syntax_type"},
    {"Typedef", "syntax_type"},
    {"PreProc", "syntax_preprocessor"},
    {"Special", "syntax_special"},
    {"Delimiter", "syntax_operator"},
    {"Todo", "ui_background", "status_warning"},
    {"Error", "status_error"},
    {"DiffAdd", "diff_added"},
    {"DiffChange", "diff_changed"},
    {"DiffDelete", "diff_removed"},
    {"DiffText", "diff_changed"},
  }

  for _, g in ipairs(groups) do
    local opts = {}
    if g[2] then opts[#opts + 1] = "fg = c[" .. string.format("%q", g[2]) .. "]" end
    if g[3] then opts[#opts + 1] = "bg = c[" .. string.format("%q", g[3]) .. "]" end
    if g[1] == "Comment" then opts[#opts + 1] = "italic = true" end
    if g[1] == "Function" or g[1] == "Title" then opts[#opts + 1] = "bold = true" end
  if g[1] == "DiffText" then opts[#opts + 1] = "bold = true" end
    lines[#lines + 1] = 'hi("' .. g[1] .. '", {' .. table.concat(opts, ", ") .. "})"
  end

  local links = {
    ["@comment"] = "Comment",
    ["@string"] = "String",
    ["@number"] = "Number",
    ["@boolean"] = "Boolean",
    ["@constant"] = "Constant",
    ["@variable"] = "Identifier",
    ["@function"] = "Function",
    ["@function.call"] = "Function",
    ["@method"] = "Function",
    ["@keyword"] = "Keyword",
    ["@operator"] = "Operator",
    ["@type"] = "Type",
    ["@constructor"] = "Type",
    ["@property"] = "Identifier",
    ["@field"] = "Identifier",
    ["@parameter"] = "Identifier",
    ["@punctuation"] = "Delimiter",
    ["@preproc"] = "PreProc",
    ["@special"] = "Special",
    ["GitSignsAdd"] = "DiffAdd",
    ["GitSignsChange"] = "DiffChange",
    ["GitSignsDelete"] = "DiffDelete",
  }

  lines[#lines + 1] = ""
  lines[#lines + 1] = "local links = {"
  for group, target in pairs(links) do
    lines[#lines + 1] = string.format("  [%q] = %q,", group, target)
  end
  lines[#lines + 1] = "}"
  lines[#lines + 1] = "for group, target in pairs(links) do"
  lines[#lines + 1] = "  hi(group, { link = target })"
  lines[#lines + 1] = "end"

  lines[#lines + 1] = ""
  lines[#lines + 1] = 'hi("DiagnosticError", { fg = c["status_error"] })'
  lines[#lines + 1] = 'hi("DiagnosticWarn", { fg = c["status_warning"] })'
  lines[#lines + 1] = 'hi("DiagnosticInfo", { fg = c["status_info"] })'
  lines[#lines + 1] = 'hi("DiagnosticHint", { fg = c["status_hint"] })'
  lines[#lines + 1] = 'hi("DiagnosticOk", { fg = c["status_success"] })'

  local ansi = {
    "ui_surface", "status_error", "accent_primary", "accent_secondary",
    "ui_border", "syntax_type", "status_info", "ui_foreground",
    "ui_muted", "status_error", "syntax_number", "ui_cursor",
    "syntax_operator", "syntax_function", "syntax_string", "ui_foreground",
  }

  lines[#lines + 1] = ""
  for i, key in ipairs(ansi) do
    lines[#lines + 1] = string.format(
      'vim.g.terminal_color_%d = c[%q]', i - 1, key
    )
  end

  return table.concat(lines, "\n") .. "\n"
end

local function generate_alacritty(p)
  local u, a, s, st = p.ui, p.accent, p.syntax, p.status

  local normal = {
    u.surface, st.error, a.primary, a.secondary,
    u.border, s.type, st.info, u.foreground,
  }

  local bright = {
    u.muted, st.error, s.number, u.cursor,
    s.operator, s["function"], s.string, u.foreground,
  }

  local keys = {"black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"}

  local function color_block(name, colors)
    local out = {"[colors." .. name .. "]"}
    for i, key in ipairs(keys) do
      out[#out + 1] = string.format('%s = "%s"', key, colors[i])
    end
    return table.concat(out, "\n")
  end

  return table.concat({
    "# Generated by scripts/generate.lua. Do not edit.",
    "",
    "[colors.primary]",
    'background = "' .. u.background .. '"',
    'foreground = "' .. u.foreground .. '"',
    "",
    "[colors.cursor]",
    'text = "' .. u.background .. '"',
    'cursor = "' .. u.cursor .. '"',
    "",
    "[colors.selection]",
    'text = "' .. u.foreground .. '"',
    'background = "' .. u.selection .. '"',
    "",
    color_block("normal", normal),
    "",
    color_block("bright", bright),
    "",
  }, "\n")
end

local function generate_obsidian(p)
  local u, a, s, st = p.ui, p.accent, p.syntax, p.status
  local light = luminance(u.background) > 0.2
  local target = light and "#000000" or "#ffffff"
  local hover = function(c) return mix(c, 10, target) end
  local tint = function(c, pct) return mix(c, pct, u.background) end

  local vars = {
    "--background-primary: " .. u.background,
    "--background-secondary: " .. u.surface,
    "--background-modifier-border: " .. u.border,
    "--background-modifier-hover: " .. mix(u.foreground, 6, "transparent"),
    "--text-normal: " .. u.foreground,
    "--text-muted: " .. s.comment,
    "--text-faint: " .. u.border,
    "--text-selection: " .. u.selection,
    "--text-on-accent: " .. u.background,
    "--text-accent: " .. a.primary,
    "--text-accent-hover: " .. hover(a.primary),
    "--text-error: " .. st.error,
    "--text-warning: " .. st.warning,
    "--text-success: " .. st.success,
    "--interactive-accent: " .. a.primary,
    "--interactive-accent-hover: " .. hover(a.primary),
    "--link-color: " .. a.primary,
    "--link-color-hover: " .. hover(a.primary),
    "--link-external-color: " .. a.secondary,
    "--link-external-color-hover: " .. hover(a.secondary),
    "--link-unresolved-color: " .. u.muted,
    "--inline-title-color: " .. a.secondary,
    "--h1-color: " .. a.primary,
    "--h2-color: " .. a.primary,
    "--h3-color: " .. a.primary,
    "--h4-color: " .. a.primary,
    "--h5-color: " .. a.primary,
    "--h6-color: " .. a.primary,
    "--code-background: " .. u.surface,
    "--code-normal: " .. u.foreground,
    "--blockquote-border-color: " .. u.border,
    "--hr-color: " .. u.border,
    "--tag-color: " .. a.primary,
    "--tag-background: " .. tint(a.primary, 12),
    "--tag-background-hover: " .. tint(a.primary, 20),
    "--checkbox-color: " .. a.primary,
    "--checkbox-marker-color: " .. u.background,
    "--text-highlight-bg: " .. tint(a.secondary, 35),
    "--titlebar-background: " .. u.surface,
    "--titlebar-background-focused: " .. u.surface,
    "--titlebar-text-color: " .. s.comment,
    "--ribbon-background: " .. u.surface,
    "--status-bar-background: " .. u.surface,
    "--status-bar-text-color: " .. s.comment,
    "--scrollbar-thumb-bg: " .. mix(u.border, 50, "transparent"),
    "--scrollbar-active-thumb-bg: " .. u.border,
  }

  local tokens = {
    { ".token.comment, .token.prolog, .token.doctype, .token.cdata", "color: " .. s.comment .. "; font-style: italic" },
    { ".token.string, .token.char, .token.attr-value, .token.regex", "color: " .. s.string },
    { ".token.number", "color: " .. s.number },
    { ".token.constant, .token.boolean, .token.symbol", "color: " .. s.constant },
    { ".token.keyword, .token.important, .token.atrule", "color: " .. s.keyword },
    { ".token.function", "color: " .. s["function"] .. "; font-weight: bold" },
    { ".token.operator, .token.punctuation", "color: " .. s.operator },
    { ".token.class-name, .token.builtin, .token.attr-name, .token.selector", "color: " .. s.type },
    { ".token.tag", "color: " .. s.special },
  }

  local out = {
    "/* Generated by scripts/generate.lua. Do not edit.",
    " * Install: copy to <vault>/.obsidian/snippets/ and enable in",
    " * Settings -> Appearance -> CSS snippets.",
    " * Set Appearance -> Base color scheme: " .. (light and "Light. */" or "Dark. */"),
    "",
    "body {",
  }
  for _, v in ipairs(vars) do out[#out + 1] = "  " .. v .. ";" end
  out[#out + 1] = "}"
  out[#out + 1] = ""
  out[#out + 1] = ".cm-cursor { border-left-color: " .. u.cursor .. "; }"
  out[#out + 1] = ""
  for _, t in ipairs(tokens) do
    out[#out + 1] = t[1] .. " { " .. t[2] .. "; }"
  end
  return table.concat(out, "\n") .. "\n"
end

local function jstr(s)
  s = s:gsub("\\", "\\\\"):gsub('"', '\\"'):gsub("\n", "\\n"):gsub("\r", "\\r"):gsub("\t", "\\t")
  return '"' .. s .. '"'
end

local function palette_json(p)
  local order = {"meta", "ui", "accent", "syntax", "status", "diff"}
  local seen = {}
  for _, s in ipairs(order) do seen[s] = true end
  for s in pairs(p) do
    if not seen[s] then order[#order + 1] = s; seen[s] = true end
  end

  local secs = {}
  for _, s in ipairs(order) do
    local keys = {}
    for k, v in pairs(p[s]) do keys[#keys + 1] = jstr(k) .. ":" .. jstr(v) end
    table.sort(keys)
    secs[#secs + 1] = jstr(s) .. ":{" .. table.concat(keys, ",") .. "}"
  end
  return "{" .. table.concat(secs, ",") .. "}"
end

local function emit_composer(payload)
  local file = assert(io.open("tools/composer.template.html", "r"),
    "tools/composer.template.html missing")
  local html = file:read("*a")
  file:close()

  assert(html:find("__PALETTES_JSON__", 1, true), "Template marker missing")
  html = html:gsub("__PALETTES_JSON__", function() return payload end)
  write("tools/composer.html", html)
end

local embedded = {}

local pipe = assert(io.popen(
  "find " .. palettes_dir .. " -maxdepth 1 -type f -name '*.toml' | sort"
))

for path in pipe:lines() do
  local palette = read_palette(path)
  validate(palette)

  local name = slug(palette.meta.name)

  write(nvim_dir .. "/findspot-" .. name .. ".lua", generate_nvim(palette))
  write(alacritty_dir .. "/" .. name .. ".toml", generate_alacritty(palette))
  write(obsidian_dir .. "/" .. name .. ".css", generate_obsidian(palette))

  embedded[#embedded + 1] = palette_json(palette)
end

pipe:close()

emit_composer("[" .. table.concat(embedded, ",") .. "]")
