local function luminance(hex)
  local function lin(part)
    local c = tonumber(part, 16) / 255
    if c <= 0.04045 then return c / 12.92 end
    return ((c + 0.055) / 1.055) ^ 2.4
  end
  return 0.2126 * lin(hex:sub(2, 3))
       + 0.7152 * lin(hex:sub(4, 5))
       + 0.0722 * lin(hex:sub(6, 7))
end

local function mix(color, pct, target)
  return string.format("color-mix(in srgb, %s %d%%, %s)", color, 100 - pct, target)
end

local function contrast_ratio(a, b)
  local la, lb = luminance(a), luminance(b)
  local lighter, darker = math.max(la, lb), math.min(la, lb)
  return (lighter + 0.05) / (darker + 0.05)
end

local function hsl(hex)
  local r = tonumber(hex:sub(2, 3), 16) / 255
  local g = tonumber(hex:sub(4, 5), 16) / 255
  local b = tonumber(hex:sub(6, 7), 16) / 255
  local maxc, minc = math.max(r, g, b), math.min(r, g, b)
  local delta = maxc - minc
  local light = (maxc + minc) / 2
  local hue, sat = 0, 0
  if delta ~= 0 then
    sat = delta / (1 - math.abs(2 * light - 1))
    if maxc == r then hue = 60 * (((g - b) / delta) % 6)
    elseif maxc == g then hue = 60 * ((b - r) / delta + 2)
    else hue = 60 * ((r - g) / delta + 4) end
  end
  return hue, sat, light
end

local function read_palette(path)
  local file = assert(io.open(path, "r"))
  local palette = {}
  local section

  for raw_line in file:lines() do
    local line = raw_line:gsub("^%s+", ""):gsub("%s+$", "")

    if line:match("^%[.+%]$") then
      section = line:match("^%[(.+)%]$")
      palette[section] = {}
    elseif line ~= "" and not line:match("^#") then
      local key, value = line:match('^([%w_]+)%s*=%s*"([^"]+)"')
      if key then
        assert(section, "Key outside section in " .. path)
        palette[section][key] = value
      end
    end
  end

  file:close()
  return palette
end

local function write(path, content)
  local file = assert(io.open(path, "w"))
  file:write(content)
  file:close()
  print("Generated " .. path)
end

local function slug(name)
  return name:lower():gsub("%s+", "-")
end

local function validate(p)
  local required = {
    ui = {"background", "surface", "foreground", "muted", "border", "selection", "cursor"},
    accent = {"primary", "secondary"},
    syntax = {"comment", "string", "number", "function", "keyword", "type", "constant", "operator", "preprocessor", "special"},
    status = {"error", "warning", "success", "info", "hint"},
    diff = {"added", "changed", "removed"},
  }

  assert(p.meta and p.meta.name, "Missing [meta].name")

  for section, keys in pairs(required) do
    assert(p[section], "Missing [" .. section .. "]")
    for _, key in ipairs(keys) do
      local value = p[section][key]
      assert(value and value:match("^#%x%x%x%x%x%x$"),
        "Invalid or missing " .. section .. "." .. key)
    end
  end
end

