local function generate_alacritty(p)
  local u, a, s, st, d = p.ui, p.accent, p.syntax, p.status, p.diff

  local normal = {
    u.surface, st.error, st.success, st.warning,
    st.info, a.primary, a.secondary, u.foreground,
  }

  local bright = {
    u.muted, st.error, d.added, st.warning,
    s.type, s["function"], s.string, u.foreground,
  }

  local keys = {"black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"}

  local function color_block(name, colors)
    local out = {"[colors." .. name .. "]"}
    for i, key in ipairs(keys) do
      out[#out + 1] = string.format('%s = "%s"', key, colors[i])
    end
    return table.concat(out, "\n")
  end

  return table.concat({
    "# Generated by scripts/generate.lua. Do not edit.",
    "",
    "[colors.primary]",
    'background = "' .. u.background .. '"',
    'foreground = "' .. u.foreground .. '"',
    "",
    "[colors.cursor]",
    'text = "' .. u.background .. '"',
    'cursor = "' .. u.cursor .. '"',
    "",
    "[colors.selection]",
    'text = "' .. u.foreground .. '"',
    'background = "' .. u.selection .. '"',
    "",
    color_block("normal", normal),
    "",
    color_block("bright", bright),
    "",
  }, "\n")
end

